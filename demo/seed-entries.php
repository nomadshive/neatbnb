<?php
/**
 * Synthetic demo data for the neatbnb demo stack.
 *
 * Creates clearly-fake listings, orders, status updates and purchases so
 * the three role dashboards have something to show. Every value below is
 * invented — NO production data is used or shipped.
 *
 * Run:  wp eval-file /demo/seed-entries.php   (driven by demo/demo.sh)
 *
 * Field IDs match the imported skeleton (setup/sql/wp_frm_definitions.sql):
 *   form 22 Listing Data | form 25 Orders | form 26 Status | form 37 Purchases
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

global $wpdb;

/* Idempotency guard: skip if orders already exist. */
$existing = (int) $wpdb->get_var(
	"SELECT COUNT(*) FROM {$wpdb->prefix}frm_items WHERE form_id = 25"
);
if ( $existing > 0 ) {
	echo "Demo entries already present — skipping seed.\n";
	return;
}

$host    = get_user_by( 'login', 'demo-host' );
$cleaner = get_user_by( 'login', 'demo-cleaner' );
if ( ! $host || ! $cleaner ) {
	echo "ERROR: demo users missing — run the user step of demo.sh first.\n";
	return;
}

/**
 * Create a Formidable entry keyed by numeric field ID.
 *
 * @return int entry ID, 0 on failure.
 */
if ( ! function_exists( 'nb_demo_entry' ) ) {
	function nb_demo_entry( $form_id, $user_id, array $fields ) {
		try {
			$id = FrmEntry::create( array(
				'form_id'   => (int) $form_id,
				'user_id'   => (int) $user_id,
				'item_meta' => $fields,
			) );
			return $id ? (int) $id : 0;
		} catch ( Throwable $e ) {
			fwrite( STDERR, " ! form {$form_id}: " . $e->getMessage() . "\n" );
			return 0;
		}
	}
}

$counts = array(
	'listings' => 0,
	'orders'   => 0,
	'statuses' => 0,
	'purchases'=> 0,
);

/* ------------------------------------------------------------------
 * 1. Listings (form 22) — the Orders form property dropdown pulls
 *    from these entries (field 277, get_values_form = 22).
 * ---------------------------------------------------------------- */
$listings = array(
	array( 'Demo Villa Riverside',   '12 Demo Lane, Cairo' ),
	array( 'Demo Apartment Skyline', '88 Sample Street, Dubai' ),
	array( 'Demo Loft Harbor',       '5 Example Avenue, Bangkok' ),
	array( 'Demo Studio Garden',     '41 Placeholder Road, Casablanca' ),
);

$property_map = array();
$n            = 1;
foreach ( $listings as $L ) {
	$id = nb_demo_entry( 22, $host->ID, array(
		194 => $L[0],                    // Listing Name
		198 => $L[1],                    // Address
		199 => '2',                      // Floor
		200 => 'B' . $n,                 // Unit Number
		201 => 'demo-wifi',              // WIFI Username
		202 => 'demo-wifi-pass',         // WIFI Password
		203 => '0000',                   // Lockbox code
		254 => '3',                      // Number of Rooms
		256 => '4',                      // Number of Beds
		255 => '2',                      // Number of Bathrooms
		259 => 'Demo Host Ltd',          // Host
		204 => $host->ID,                // User ID
		205 => 'host',                   // User Role (hidden)
		207 => (string) $n,              // Property ID (hidden display number)
		286 => '85',                     // Size in m²
		396 => 'Synthetic demo listing (generated by demo/seed-entries.php).',
	) );
	if ( $id ) {
		$counts['listings'] ++;
		$property_map[] = $id . ' = ' . $n;
	}
	$n ++;
}

/* Register the demo listings in the property map (Settings → Neatbnb Ops). */
if ( $property_map ) {
	$saved = get_option( 'nb_ops_settings', array() );
	$saved = is_array( $saved ) ? $saved : array();
	$saved['property_map'] = implode( "\n", $property_map );
	update_option( 'nb_ops_settings', $saved );
}

/* ------------------------------------------------------------------
 * 2. Orders (form 25) — submitted by the demo host.
 * ---------------------------------------------------------------- */
$listing_ids = $wpdb->get_col(
	"SELECT id FROM {$wpdb->prefix}frm_items WHERE form_id = 22 ORDER BY id"
);
if ( ! $listing_ids ) {
	echo "ERROR: no demo listings were created.\n";
	return;
}

$orders = array(
	// date,        time,  task type,    sub type,                 budget, description,                            listing idx
	array( '2026-11-27', '10:00', 'Cleaning',    'Deep Cleaning',          '120', 'Deep clean of the living room and kitchen.', 0 ),
	array( '2026-11-28', '09:00', 'Cleaning',    'Normal Cleaning',        '80',  'Weekly normal cleaning.',                    1 ),
	array( '2026-11-30', '14:00', 'Maintenance', 'Aluminum',               '200', 'Aluminium balcony door adjustment.',         2 ),
	array( '2026-12-01', '11:00', 'Maintenance', 'Appliances maintenance','150', 'Fridge and washing machine service.',        3 ),
	array( '2026-12-03', '13:30', 'Cleaning',    'Deep Cleaning',          '130', 'Deep cleaning before a new guest arrival.',  0 ),
	array( '2026-12-05', '16:00', 'Other',       '',                       '60',  'Miscellaneous handyman visit.',              1 ),
);

$order_rows = array();
foreach ( $orders as $O ) {
	$listing_id = $listing_ids[ $O[6] % count( $listing_ids ) ];
	$fields     = array(
		281 => $O[0],                       // Date
		284 => $O[1],                       // Time
		277 => (string) $listing_id,        // PropertyID (listing entry ID)
		433 => $O[2],                       // Type of task
		285 => 'Synthetic demo task created by demo/seed-entries.php.',
		436 => $O[5],                       // Task description
		455 => $O[4],                       // Task budget cost
		279 => $host->ID,                   // User ID
	);
	if ( 'Cleaning' === $O[2] ) {
		$fields[278] = $O[3];               // Type of Cleaning
	} elseif ( 'Maintenance' === $O[2] ) {
		$fields[434] = $O[3];               // Type of Maintenance
	}
	$id = nb_demo_entry( 25, $host->ID, $fields );
	if ( $id ) {
		$counts['orders'] ++;
		$order_rows[] = array(
			'id'      => $id,
			'type'    => $O[2],
			'address' => $listings[ $O[6] % count( $listings ) ][1],
		);
	}
}

/* ------------------------------------------------------------------
 * 3. Status updates (form 26) — submitted by the demo cleaner.
 * ---------------------------------------------------------------- */
$statuses = array( 'APPROVED', 'APPROVED', 'CANCELLED', 'APPROVED', 'UNAVAILABLE', 'APPROVED' );
foreach ( $order_rows as $i => $O ) {
	$status = isset( $statuses[ $i ] ) ? $statuses[ $i ] : 'APPROVED';
	$fields = array(
		291 => (string) $O['id'],           // Task ID (the order entry)
		439 => $O['type'],                  // Type of task
		295 => $status,                     // Status
		463 => $cleaner->ID,                // User ID
	);
	if ( 'APPROVED' === $status ) {
		// Assigned worker: cleaning → 292/297, maintenance → 454.
		if ( 'Maintenance' === $O['type'] ) {
			$fields[454] = (string) $cleaner->ID;
		} else {
			$fields[292] = (string) $cleaner->ID;
		}
	}
	if ( nb_demo_entry( 26, $cleaner->ID, $fields ) ) {
		$counts['statuses'] ++;
	}
}

/* ------------------------------------------------------------------
 * 4. Purchases (form 37) — two approved tasks, submitted by the host.
 * ---------------------------------------------------------------- */
$purchase_amounts = array( '150', '220' );
$pi               = 0;
foreach ( $order_rows as $i => $O ) {
	if ( $pi >= count( $purchase_amounts ) ) {
		break;
	}
	if ( ! isset( $statuses[ $i ] ) || 'APPROVED' !== $statuses[ $i ] ) {
		continue;
	}
	$id = nb_demo_entry( 37, $host->ID, array(
		526 => (string) $O['id'],           // Task ID
		529 => $purchase_amounts[ $pi ],    // Amount
		530 => $O['address'],               // Property Address
	) );
	if ( $id ) {
		$counts['purchases'] ++;
	}
	$pi ++;
}

echo "\nSeeded demo data:\n";
foreach ( $counts as $k => $v ) {
	printf( "  %-10s %d\n", $k, $v );
}
